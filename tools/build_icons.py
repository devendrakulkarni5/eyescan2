"""Bundle the Lucide icon set for offline use.

    npm pack lucide-static            (once, anywhere)  ->  lucide-static-<ver>.tgz
    tar -xzf lucide-static-*.tgz
    python tools/build_icons.py <path to extracted "package" folder>

Writes ui/vendor/lucide.js (window.LUCIDE = {name: inner-svg-markup}) and the ISC licence next to it.
Lucide is ISC licensed: https://lucide.dev/license
"""
import json
import re
import shutil
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(__file__).resolve().parents[1] / "ui" / "vendor"
out.mkdir(parents=True, exist_ok=True)
icons = {}
for f in sorted((src / "icons").glob("*.svg")):
    text = f.read_text(encoding="utf-8")
    inner = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    inner = inner[inner.index(">", inner.index("<svg")) + 1: inner.rindex("</svg>")]
    inner = re.sub(r"\s+", " ", inner).replace("> <", "><").replace(" />", "/>").strip()
    icons[f.stem] = inner
ver = json.loads((src / "package.json").read_text(encoding="utf-8"))["version"]
js = f"/* Lucide icons v{ver} (ISC licence, see LICENSE-lucide.txt). Generated by tools/build_icons.py - do not edit. */\nwindow.LUCIDE = " + json.dumps(icons, separators=(",", ":")) + ";\n"
(out / "lucide.js").write_text(js, encoding="utf-8")
shutil.copy(src / "LICENSE", out / "LICENSE-lucide.txt")
print(f"{len(icons)} icons, {len(js) // 1024} KB")
